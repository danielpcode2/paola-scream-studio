import Foundation

/// Translated UI string for the language chosen in Settings.
func tr(_ key: String) -> String {
    guard let entry = Strings.table[key] else { return key }
    return AppLanguage.current == .es ? entry.es : entry.en
}

/// Translated format string (`%@`, `%d`, …).
func tr(_ key: String, _ arguments: CVarArg...) -> String {
    String(format: tr(key), arguments: arguments)
}

